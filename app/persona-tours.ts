/**
 * Туры по персонажам «На примере»: у каждого человека свой короткий тур по «Профилю» вместо общего «Как читать профиль».
 * Тексты — про то, что видно на экране именно у этого человека; числа берутся из живого `PositionView`, чтобы не разойтись с экраном.
 * Чистая функция `personaTourSteps` — для теста; запуск — `personaTour` (app/tours.ts).
 */
import type { PositionView } from '../engine/index';
import type { PersonaId } from './personas';
import type { TourStep } from './tour';

/** Запас — округление вниз до десятых, как на «Профиле». */
const nfDown = (x: number): string => (Math.floor(x * 10 + 1e-9) / 10).toFixed(1).replace('.', ',');
/** Тенге в тысячах, округлённо: 110000 → «110 тыс ₸». */
const kt = (t: number): string => (t >= 1_000_000 ? `${(t / 1_000_000).toFixed(1).replace('.', ',')} млн ₸` : `${Math.round(t / 1000)} тыс ₸`);

const OTHERS = ' Остальные примеры — «Ещё → На примере».';

export function personaTourSteps(id: PersonaId, v: PositionView): TourStep[] {
  const weak = v.weak ? `${v.weak.directionName}${v.weak.indicator ? ` · ${v.weak.indicator.label}` : ''}` : null;
  switch (id) {
    case 'berik':
      return [
        { target: '[data-tour=level]', title: 'Берик: ступень 1', text: `Потерял стабильную работу, расходы больше доходов${v.runway.deficit > 0 ? ` на ${kt(v.runway.deficit)} в месяц` : ''}, запаса нет, долги растут. Экран тёплого цвета нарочно: здесь нет упрёков, только то, что происходит.` },
        { target: '.pos-now', title: 'Главное сейчас', text: 'Одна цифра, с которой всё начинается: разница между доходом и расходами. «Что можно сделать» ведёт к тратам, где можно выиграть.' },
        { target: '[data-tour=path]', title: 'Дорога до ступени 2', text: `Условия — не приговор, а список. «Как выполнить» собирает путь из этих же цифр: сколько откладывать и на чём можно сэкономить.${OTHERS}` },
      ];
    case 'serik':
      return [
        { target: '[data-tour=level]', title: 'Серик: ступень 2', text: v.held ?? 'Стабильная зарплата, но запаса почти нет: он удерживает ступень.' },
        { target: '[data-tour=path]', title: 'Что не закрыто', text: `Осталось закрыть запас: «Как выполнить» показывает, сколько не хватает и к какому месяцу он наберётся. Платежи по рассрочке на телефон кончатся — освободившиеся деньги в сроке уже учтены.${OTHERS}` },
      ];
    case 'aliya':
      return [
        { target: '[data-tour=level]', title: 'Алия: ступень 3', text: `Подушка есть: запас ${nfDown(v.money.reserveEssentialMonths)} мес. До «${v.next?.name ?? 'следующей ступени'}» — ${v.next?.needs.join(', ') ?? 'совсем немного'}: она на границе ступеней.` },
        { target: '[data-tour=dirs]', title: 'Что тянет вниз', text: 'Ниже всех показателей — «Долговая нагрузка»: платежи по ипотеке — около трети дохода. Ипотека привязана к квартире, поэтому долг оценивается по доле в стоимости жилья, а не как обычный.' },
        { target: '[data-tour=path]', title: 'Как выполнить', text: `Запас уже больше шести месяцев, поэтому «Как выполнить» показывает не деньги, а слабые показатели: что именно подтянуть.${OTHERS}` },
      ];
    case 'olzhas':
      return [
        { target: '[data-tour=level]', title: 'Олжас: ступень 4', text: 'Запас не меньше шести месяцев, все три направления от 60 и выше: один удар — потеря работы, крупная трата — не ломает план.' },
        { target: '[data-tour=weak]', title: 'Слабее всего', text: `${weak ? `${weak}.` : 'Слабое место.'} Для ступени это не проблема, а подсказка, где ещё есть запас роста.` },
        { target: '[data-tour=money]', title: 'Следующая цель', text: `Дальше — независимость: «Подробнее» → «Независимость» показывает, сколько капитала нужно, чтобы можно было не работать.${OTHERS}` },
      ];
    case 'dantal':
      return [
        { target: '[data-tour=level]', title: 'Дантал: ступень 5', text: 'Капитал и доход от него покрывают расходы с запасом: независимость подтверждена. Можно не работать ради денег.' },
        { target: '[data-tour=weak]', title: 'Откладывать уже не обязательно', text: 'Вместо слабого места — пояснение, почему низкая «Динамика» тут не упрёк. Сами оценки не спрятаны: они видны в листе направления, если нажать на него.' },
        { target: '[data-tour=money]', title: 'Запас в сотни месяцев', text: `Это не опечатка: капитал во много раз больше расходов. Здесь важнее не копить, а не растратить его быстрее, чем он работает.${OTHERS}` },
      ];
  }
}
