import type { Icon } from './icons';
export type IconKey = Icon;

export interface Slide {
  icon: IconKey;
  title: string;
  text: string;
  /** Где это найти — подсказка, не ссылка. */
  where?: string;
  /** Плашка над заголовком: «Новое», «Возможность». */
  badge?: string;
  /** Кнопка «Показать на экране» — подсказка поверх настоящего интерфейса (D191). */
  tour?: 'mode';
}

export interface Release {
  /** Номер выпуска — дата; по нему решаем, показывать ли окно ещё раз. */
  id: string;
  version: string;
  slides: Slide[];
}

