/**
 * «Как пользоваться» (D94): что это за приложение, когда его открывать и как решить типичные задачи.
 * Построено по задачам человека, а не по функциям; словарь — те же тексты, что в кнопках ⓘ (один источник).
 */
import { h } from '../dom';
import { HELP } from '../help-text';
import { sub } from '../ui';

const SEEN_KEY = 'capital-os.help-seen';

/** Видел ли человек справку (для подсказки «Впервые здесь?» на «Обзоре»). Хранилище браузера может быть недоступно — тогда считаем, что видел. */
export function helpSeen(): boolean {
  try {
    return localStorage.getItem(SEEN_KEY) === '1';
  } catch {
    return true;
  }
}

export function markHelpSeen(): void {
  try {
    localStorage.setItem(SEEN_KEY, '1');
  } catch {
    /* не страшно: подсказка просто покажется ещё раз */
  }
}

/** Одна задача: вопрос человека → короткие шаги. */
function task(q: string, steps: string[], tip?: string): HTMLElement {
  return h(
    'details',
    { class: 'fold help-task', 'data-key': `help:${q}` },
    h('summary', null, q),
    h('ol', { class: 'help-steps' }, steps.map((s) => h('li', null, s))),
    tip ? h('p', { class: 'muted' }, tip) : null,
  );
}

export function renderHelp(): HTMLElement {
  markHelpSeen();
  const key = (t: string) => t.replace(/[«»]/g, '');
  const terms = Object.values(HELP).sort((a, b) => key(a.title).localeCompare(key(b.title), 'ru'));
  return h(
    'div',
    { class: 'screen help' },
    h(
      'section',
      { class: 'card stack tight' },
      h('h2', null, 'Что это'),
      h(
        'p',
        null,
        'Capital OS — помощник к MoneyManager. Учёт ты ведёшь там, а сюда загружаешь его бэкап и видишь то, чего MoneyManager не показывает:',
      ),
      h(
        'ul',
        { class: 'help-list' },
        h('li', null, 'сколько денег свободно до следующего дохода;'),
        h('li', null, 'как поделить пришедшие деньги между целями;'),
        h('li', null, 'успеваешь ли накопить к нужному сроку;'),
        h('li', null, 'что будет с деньгами через полгода — три года и что изменит крупное решение.'),
      ),
      h('p', { class: 'muted' }, 'Приложение ничего не переводит и не трогает счета — только считает и подсказывает.'),
    ),
    h(
      'section',
      { class: 'card stack tight' },
      h('h2', null, 'Когда открывать'),
      h(
        'ul',
        { class: 'help-list' },
        h('li', null, h('strong', null, 'Пришли деньги'), ' (зарплата, стипендия) — решить, сколько отложить и на что.'),
        h('li', null, h('strong', null, 'Перед крупной тратой или рассрочкой'), ' — посмотреть, что она сдвинет.'),
        h('li', null, h('strong', null, 'Раз в месяц'), ' — загрузить свежий бэкап и скачать копию своих настроек.'),
      ),
      h('p', { class: 'muted' }, 'Каждый день открывать не нужно: 2–4 раза в месяц достаточно.'),
    ),
    sub('Как сделать'),
    h(
      'div',
      { class: 'stack tight' },
      task('Загрузить свежие данные', [
        'В MoneyManager сделай резервную копию — получится файл .mmbackup.',
        'Здесь: «Ещё → Данные → Импорт», выбери этот файл.',
        'Проверь сверку: если все счета сошлись — «Принять импорт».',
      ], 'Новый бэкап заменяет операции. Разметка, цели, доходы и рассрочки остаются.'),
      task('Пришли деньги — что с ними делать', [
        'Открой «Доход» и введи, сколько пришло и на какой счёт.',
        'Приложение вычтет платежи по долгам и обычные траты до следующего дохода и покажет, сколько можно распределить.',
        'Выбери вариант распределения и нажми «Поставить метки».',
      ], 'Метки — это пометки «эти деньги за такой-то целью». Деньги остаются на счёте; переводить их ты решаешь сам.'),
      task('Хочу накопить на что-то', [
        '«Цели → ＋ Цель»: название, сколько нужно и к какому сроку (срок можно не указывать).',
        'Если уже есть отложенные деньги — «Закрепить деньги» за целью.',
        'В «Прогнозе» в разделе «Когда достигнешь целей» видно, к какому месяцу накопишь; нажми на цель — увидишь почему.',
      ]),
      task('Что будет, если…', [
        '«Прогноз → А что если…».',
        '«Запланировать событие» — то, что точно будет (новая работа, аренда, покупка): войдёт в прогноз.',
        '«Проверить одно решение» — сравнить прогноз с решением и без него.',
      ]),
      task('Почему цифра именно такая', [
        'Под главными числами есть «Как посчитано ›» — там видно, из чего число сложилось.',
        'Кружок ⓘ рядом со словом объясняет само понятие.',
      ]),
      task('Цифры выглядят странно', [
        'Посмотри на метку вверху экрана. Серая «Данные от …» — всё в порядке.',
        'Жёлтая «Приблизительно» — приложению не хватает ответов: нажми на неё, там список.',
        'Красная «Сверка» — бэкап прочитан с расхождением: таким цифрам верить нельзя, загрузи бэкап заново.',
      ]),
      task('Не потерять настройки', [
        'Все данные хранятся только в этом браузере на этом устройстве.',
        '«Ещё → Данные → Бэкап → Скачать бэкап» — раз в месяц и перед сменой телефона.',
        'На новом устройстве: «Восстановить из файла».',
      ]),
    ),
    sub('Экраны'),
    h(
      'ul',
      { class: 'help-list card' },
      h('li', null, h('strong', null, 'Обзор'), ' — сколько свободно до следующего дохода, ближайшие платежи, счета.'),
      h('li', null, h('strong', null, 'Цели'), ' — на что копишь и сколько уже есть.'),
      h('li', null, h('strong', null, 'Доход'), ' — как поделить пришедшие деньги.'),
      h('li', null, h('strong', null, 'Прогноз'), ' — что будет с деньгами и целями дальше.'),
      h('li', null, h('strong', null, 'Ещё'), ' — данные, разметка трат, счета, доходы, долги, настройки.'),
    ),
    sub('Словарь'),
    h(
      'div',
      { class: 'stack tight' },
      terms.map((t) => h('details', { class: 'fold', 'data-key': `help:term:${t.title}` }, h('summary', null, t.title), h('p', null, t.text))),
    ),
  );
}
