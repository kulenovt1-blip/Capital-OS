/**
 * Туры по персонажам «На примере»: у каждого человека свой короткий тур по «Профилю» вместо общего «Как читать профиль».
 * Тексты — про то, что видно на экране именно у этого человека; числа берутся из живого `PositionView`, чтобы не разойтись с экраном.
 * Чистая функция `personaTourSteps` — для теста; запуск — `personaTour` (app/tours.ts).
 */
import type { PositionView } from '../engine/index';
import type { PersonaId } from './personas';
import type { TourStep } from './tour';

/** Запас — округление вниз до десятых, как на «Профиле». */
const nfDown = (x: number): string => (Math.floor(x * 10 + 1e-9) / 10).toFixed(1).replace('.', ',');
/** Тенге в тысячах, округлённо: 110000 → «110 тыс ₸». */
const kt = (t: number): string => (t >= 1_000_000 ? `${(t / 1_000_000).toFixed(1).replace('.', ',')} млн ₸` : `${Math.round(t / 1000)} тыс ₸`);

const OTHERS = ' Остальные примеры — «Ещё → На примере».';

export function personaTourSteps(id: PersonaId, v: PositionView): TourStep[] {
  const weak = v.weak ? `${v.weak.directionName}${v.weak.indicator ? ` · ${v.weak.indicator.label}` : ''}` : null;
  switch (id) {
    case 'berik':
      return [
        { target: '[data-tour=level]', title: 'Берик: ступень 1', text: `Потерял стабильную работу, расходы больше доходов${v.runway.deficit > 0 ? ` на ${kt(v.runway.deficit)} в месяц` : ''}, запаса нет, долги растут. Экран тёплого цвета нарочно: здесь нет упрёков, только то, что происходит.` },
        { target: '.pos-now', title: 'Главное сейчас', text: 'Одна цифра, с которой всё начинается: разница между доходом и расходами. «Что можно сделать» показывает, где траты крупнее всего.' },
        { target: '[data-tour=path]', title: 'План до ступени 2', text: `Первый шаг один — выйти в плюс: пока минус, откладывать бесполезно. «Как дойти» раскладывает это по шагам.${OTHERS}` },
      ];
    case 'serik':
      return [
        { target: '[data-tour=level]', title: 'Серик: ступень 2', text: v.held ?? 'Стабильная зарплата, но запаса почти нет: он удерживает ступень.' },
        { target: '[data-tour=path]', title: 'Что не закрыто', text: `Осталось закрыть запас: «Как дойти» показывает, сколько не хватает и к какому месяцу он наберётся. Платежи по рассрочке на телефон кончатся — освободившиеся деньги в сроке уже учтены.${OTHERS}` },
      ];
    case 'aliya':
      return [
        { target: '[data-tour=level]', title: 'Алия: ступень 3', text: `Подушка есть: запас ${nfDown(v.money.reserveEssentialMonths)} мес. До «${v.next?.name ?? 'следующей ступени'}» не хватает совсем немного общей оценки: она на границе ступеней.` },
        { target: '[data-tour=dirs]', title: 'Что тянет вниз', text: 'Ниже всех показателей — «Долговая нагрузка»: платежи по ипотеке — около трети дохода. Ипотека привязана к квартире, поэтому долг оценивается по доле в стоимости жилья, а не как обычный. Сама квартира — имущество: в капитале она есть, а в деньгах и запасе — нет.' },
        { target: '[data-tour=path]', title: 'План', text: `Запас уже больше шести месяцев, поэтому в плане осталась только общая оценка: шкала показывает, сколько её не хватает, а «Как дойти» — что именно подтянуть.${OTHERS}` },
      ];
    case 'olzhas':
      return [
        { target: '[data-tour=level]', title: 'Олжас: ступень 4', text: 'Запас больше шести месяцев, все три направления от 60 и выше: один удар — потеря работы, крупная трата — не ломает план.' },
        { target: '[data-tour=path]', title: 'До ступени 5', text: `Чтобы не смотреть на цены, нужны деньги на год обычной жизни и свобода в каждой зарплате. У Олжаса автокредит забирает большую часть дохода на обязательное — когда кредит кончится, условие выполнится само.${OTHERS}` },
      ];
    case 'dantal':
      return [
        { target: '[data-tour=level]', title: 'Дантал: ступень 5', text: 'Живёт на проценты по вкладам и тратит меньше половины того, что они приносят. Денег на годы обычной жизни: лишняя покупка ничего не ломает.' },
        { target: '[data-tour=weak]', title: 'Верхняя ступень', text: 'Дальше ступеней нет. Здесь важно не копить больше, а не растерять: чтобы траты не росли быстрее дохода.' },
        { target: '[data-tour=money]', title: 'Запас в сотни месяцев', text: `Это не опечатка: денег во много раз больше, чем уходит за месяц.${OTHERS}` },
      ];
  }
}
